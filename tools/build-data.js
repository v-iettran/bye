#!/usr/bin/env node
/* Regenerates game/js/data.js from the `characters` array in script.js.
   Only id, name, stats and skills (key, name, description) are copied.
   netId, image paths and anything from message.js never reach game/.
   Run from the repo root:  node tools/build-data.js */
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const src = fs.readFileSync(path.join(root, 'script.js'), 'utf8');

const start = src.indexOf('[', src.indexOf('const characters'));
let depth = 0, end = -1, quote = null;
for (let i = start; i < src.length; i++) {
  const c = src[i];
  if (quote) {
    if (c === '\\') i++;
    else if (c === quote) quote = null;
  } else if (c === '"' || c === "'" || c === '`') quote = c;
  else if (c === '[') depth++;
  else if (c === ']' && --depth === 0) { end = i + 1; break; }
}
if (start < 0 || end < 0) throw new Error('characters array not found in script.js');
const characters = new Function('return ' + src.slice(start, end))();

const out = characters.map((c) => ({
  id: c.id,
  name: c.name,
  stats: { humor: c.stats.humor, kindness: c.stats.kindness, energy: c.stats.energy, weird: c.stats.weird },
  skills: c.skills.map((s) => ({
    key: s.key,
    name: s.name.replace(/^Ultimate\s*[-–]\s*/i, ''),
    description: s.description,
  })),
}));

const text = JSON.stringify(out, null, 1);
if (/netId|images\//.test(text)) throw new Error('private field leaked into game data');
fs.writeFileSync(
  path.join(root, 'game/js/data.js'),
  '/* Generated by tools/build-data.js from ../script.js. Do not edit by hand. */\n' +
    'window.RA = window.RA || {};\nRA.characters = ' + text + ';\n'
);
console.log('wrote game/js/data.js:', out.length, 'characters,', out.reduce((n, c) => n + c.skills.length, 0), 'skills');
